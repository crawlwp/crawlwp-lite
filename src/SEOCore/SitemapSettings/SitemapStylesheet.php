	/**
	 * Get the stylesheet URL for a given sitemap type.
	 *
	 * @param string $type Stylesheet type: 'custom', 'video', or 'news'.
	 * @return string
	 */
	public static function get_stylesheet_url(string $type = self::CUSTOM_TYPE): string
	{
		global $wp_rewrite;

		$normalized = self::normalize_type($type) ?? self::CUSTOM_TYPE;

		$using_permalinks = isset($wp_rewrite) && is_object($wp_rewrite) && method_exists($wp_rewrite, 'using_permalinks') && $wp_rewrite->using_permalinks();

		if ($using_permalinks) {
			$url = home_url("/wp-sitemap-{$normalized}.xsl");
		} else {
			$url = home_url("/?sitemap-stylesheet={$normalized}");
		}

		$url = apply_filters("crawlwp_sitemap_{$normalized}_stylesheet_url", $url);

		return (string) apply_filters('crawlwp_sitemap_stylesheet_url', $url, $normalized);
	}

	/**
	 * Instance wrapper for get_stylesheet_url.
	 *
	 * @param string $type Stylesheet type: 'custom', 'video', or 'news'.
	 * @return string
	 */
	public function get_sitemap_stylesheet_url(string $type = self::CUSTOM_TYPE): string
	{
		return self::get_stylesheet_url($type);
	}

	/**
	 * Gets the CSS to be included in sitemap XSL stylesheets.
	 *
	 * @return string
	 */
	public function get_stylesheet_css(): string
	{
		$css = '';
		if (class_exists('\WP_Sitemaps_Stylesheet')) {
			$stylesheet = new \WP_Sitemaps_Stylesheet();
			$css = $stylesheet->get_stylesheet_css();
		} else {
			$text_align = function_exists('is_rtl') && is_rtl() ? 'right' : 'left';
			$css = <<<EOF

					body {
						font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Oxygen-Sans, Ubuntu, Cantarell, "Helvetica Neue", sans-serif;
						color: #444;
					}

					#sitemap {
						max-width: 980px;
						margin: 0 auto;
					}

					#sitemap__table {
						width: 100%;
						border: solid 1px #ccc;
						border-collapse: collapse;
					}

			 		#sitemap__table tr td.loc {
						direction: ltr;
					}

					#sitemap__table tr th {
						text-align: {$text_align};
					}

					#sitemap__table tr td,
					#sitemap__table tr th {
						padding: 10px;
					}

					#sitemap__table tr:nth-child(odd) td {
						background-color: #eee;
					}

					a:hover {
						text-decoration: none;
					}

EOF;
		}

		$extra = '
					#sitemap__table td.thumbnail {
						width: 130px;
						text-align: center;
					}
					#sitemap__table td.video-title,
					#sitemap__table td.news-title {
						font-weight: 500;
					}
					#sitemap__table td.video-desc {
						color: #646970;
						font-size: 13px;
					}
					#sitemap__table td.pubdate,
					#sitemap__table td.publication {
						color: #646970;
						font-size: 13px;
						white-space: nowrap;
					}
		';

		return apply_filters('crawlwp_sitemaps_stylesheet_css', $css . $extra);
	}
}
