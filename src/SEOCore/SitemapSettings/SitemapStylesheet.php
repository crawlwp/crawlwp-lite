<?php

namespace Mihdan\IndexNow\SEOCore\SitemapSettings;

/**
 * Provides XSL stylesheets to style custom, video, and news sitemaps.
 *
 * Mirrors the WordPress core WP_Sitemaps_Stylesheet design (render_stylesheet(),
 * get_sitemap_stylesheet(), get_stylesheet_css()).
 */
class SitemapStylesheet
{
	const CUSTOM_TYPE = 'custom';
	const VIDEO_TYPE  = 'video';
	const NEWS_TYPE   = 'news';

	public function __construct()
	{
		add_action('init', [$this, 'add_rewrite_rules']);
		add_filter('query_vars', [$this, 'query_vars']);
		add_action('template_redirect', [$this, 'maybe_render'], 1);
	}

	/**
	 * Add rewrite rules for the custom, video, and news sitemap XSL stylesheets.
	 */
	public function add_rewrite_rules(): void
	{
		add_rewrite_rule('^wp-sitemap-custom\.xsl$', 'index.php?sitemap-stylesheet=custom', 'top');
		add_rewrite_rule('^wp-sitemap-crawlwpcustom\.xsl$', 'index.php?sitemap-stylesheet=custom', 'top');

		add_rewrite_rule('^wp-sitemap-video\.xsl$', 'index.php?sitemap-stylesheet=video', 'top');
		add_rewrite_rule('^wp-sitemap-crawlwpvideo\.xsl$', 'index.php?sitemap-stylesheet=video', 'top');

		add_rewrite_rule('^wp-sitemap-news\.xsl$', 'index.php?sitemap-stylesheet=news', 'top');
		add_rewrite_rule('^wp-sitemap-crawlwpnews\.xsl$', 'index.php?sitemap-stylesheet=news', 'top');
	}

	/**
	 * Ensure sitemap-stylesheet query var is registered.
	 *
	 * @param string[] $vars
	 * @return string[]
	 */
	public function query_vars(array $vars): array
	{
		if (!in_array('sitemap-stylesheet', $vars, true)) {
			$vars[] = 'sitemap-stylesheet';
		}

		return $vars;
	}

	/**
	 * Normalize custom, video, or news stylesheet type string.
	 */
	public static function normalize_type(string $type): ?string
	{
		return match ($type) {
			'custom', 'crawlwpcustom' => self::CUSTOM_TYPE,
			'video', 'crawlwpvideo'   => self::VIDEO_TYPE,
			'news', 'crawlwpnews'     => self::NEWS_TYPE,
			default                   => null,
		};
	}

	/**
	 * Render the stylesheet if requested on template_redirect.
	 */
	public function maybe_render(): void
	{
		$type = sanitize_text_field((string) get_query_var('sitemap-stylesheet'));
		if ($type === '') {
			return;
		}

		$normalized = self::normalize_type($type);
		if ($normalized === null) {
			return;
		}

		if ($normalized === self::VIDEO_TYPE && SitemapSettings::get('video_enabled', 'off') !== 'on') {
			if (function_exists('wp_die')) {
				wp_die(
					esc_html__('The Video Sitemap is disabled. Enable it under Settings → Advanced → Sitemap.', 'mihdan-index-now'),
					esc_html__('Video Sitemap disabled', 'mihdan-index-now'),
					['response' => 404]
				);
			}
			return;
		}

		if ($normalized === self::NEWS_TYPE && SitemapSettings::get('news_enabled', 'off') !== 'on') {
			if (function_exists('wp_die')) {
				wp_die(
					esc_html__('The News Sitemap is disabled. Enable it under Settings → Advanced → Sitemap.', 'mihdan-index-now'),
					esc_html__('News Sitemap disabled', 'mihdan-index-now'),
					['response' => 404]
				);
			}
			return;
		}

		$this->render_stylesheet($normalized);
	}

	/**
	 * Renders the XSL stylesheet depending on the sitemap type.
	 *
	 * @param string $type Stylesheet type. 'custom', 'video', or 'news'.
	 * @return never
	 */
	public function render_stylesheet(string $type)
	{
		if (!headers_sent()) {
			header('Content-Type: application/xml; charset=UTF-8');
		}

		echo $this->get_sitemap_stylesheet($type);

		exit;
	}

	/**
	 * Returns the escaped XSL for the given sitemap type.
	 *
	 * @param string $type Stylesheet type. Either 'custom', 'video', or 'news'.
	 * @return string
	 */
	public function get_sitemap_stylesheet(string $type = self::CUSTOM_TYPE): string
	{
		$normalized = self::normalize_type($type) ?? self::CUSTOM_TYPE;

		return match ($normalized) {
			self::VIDEO_TYPE => $this->get_video_sitemap_stylesheet(),
			self::NEWS_TYPE  => $this->get_news_sitemap_stylesheet(),
			default          => $this->get_custom_sitemap_stylesheet(),
		};
	}

	/**
	 * Returns the escaped XSL for custom URLs sitemaps.
	 *
	 * @return string
	 */
	public function get_custom_sitemap_stylesheet(): string
	{
		$css         = $this->get_stylesheet_css();
		$title       = esc_xml(__('Custom URLs XML Sitemap', 'mihdan-index-now'));
		$description = sprintf(
			/* translators: %s: CrawlWP link */
			esc_xml(__('This XML Sitemap is generated by %s to make your content more visible for search engines.', 'mihdan-index-now')),
			'CrawlWP'
		);
		$description = str_replace('CrawlWP', '<a target="_blank" href="https://crawlwp.com/">CrawlWP SEO plugin</a>', $description);

		$learn_more  = sprintf(
			'<a href="%s">%s</a>',
			esc_url(__('https://www.sitemaps.org/')),
			esc_xml(__('Learn more about XML sitemaps.'))
		);

		$text = sprintf(
			/* translators: %s: Number of URLs. */
			esc_xml(__('Number of URLs in this XML Sitemap: %s.', 'mihdan-index-now')),
			'<xsl:value-of select="count( sitemap:urlset/sitemap:url )" />'
		);

		$lang    = function_exists('get_language_attributes') ? get_language_attributes('html') : 'lang="en-US"';
		$url     = esc_xml(__('URL'));
		$lastmod = esc_xml(__('Last Modified'));

		$xsl_content = <<<XSL
<?xml version="1.0" encoding="UTF-8"?>
<xsl:stylesheet
		version="1.0"
		xmlns:xsl="http://www.w3.org/1999/XSL/Transform"
		xmlns:sitemap="http://www.sitemaps.org/schemas/sitemap/0.9"
		exclude-result-prefixes="sitemap"
		>

	<xsl:output method="html" encoding="UTF-8" indent="yes" />

	<!--
	  Set variables for whether lastmod occurs for any url in the sitemap.
	  We do this up front because it can be expensive in a large sitemap.
	  -->
	<xsl:variable name="has-lastmod" select="count( /sitemap:urlset/sitemap:url/sitemap:lastmod )" />

	<xsl:template match="/">
		<html {$lang}>
			<head>
				<title>{$title}</title>
				<style>
					{$css}
				</style>
			</head>
			<body>
				<div id="sitemap">
					<div id="sitemap__header">
						<h1>{$title}</h1>
						<p>{$description}</p>
						<p>{$learn_more}</p>
					</div>
					<div id="sitemap__content">
						<p class="text">{$text}</p>
						<table id="sitemap__table">
							<thead>
								<tr>
									<th class="loc">{$url}</th>
									<xsl:if test="\$has-lastmod">
										<th class="lastmod">{$lastmod}</th>
									</xsl:if>
								</tr>
							</thead>
							<tbody>
								<xsl:for-each select="sitemap:urlset/sitemap:url">
									<tr>
										<td class="loc"><a href="{sitemap:loc}"><xsl:value-of select="sitemap:loc" /></a></td>
										<xsl:if test="\$has-lastmod">
											<td class="lastmod"><xsl:value-of select="sitemap:lastmod" /></td>
										</xsl:if>
									</tr>
								</xsl:for-each>
							</tbody>
						</table>
					</div>
				</div>
			</body>
		</html>
	</xsl:template>
</xsl:stylesheet>

XSL;

		$xsl_content = apply_filters('crawlwp_sitemaps_custom_stylesheet_content', $xsl_content);

		return (string) apply_filters('wp_sitemaps_stylesheet_content', $xsl_content);
	}

	/**
	 * Returns the escaped XSL for video sitemaps.
	 *
	 * @return string
	 */
	public function get_video_sitemap_stylesheet(): string
	{
		$css         = $this->get_stylesheet_css();
		$title       = esc_xml(__('Video XML Sitemap', 'mihdan-index-now'));
		$description = sprintf(
			/* translators: %s: CrawlWP link */
			esc_xml(__('This XML Sitemap is generated by WordPress, and improved by %s to make your video content more visible for search engines.', 'mihdan-index-now')),
			'CrawlWP'
		);
		$description = str_replace('CrawlWP', '<a target="_blank" href="https://crawlwp.com">CrawlWP SEO plugin</a>', $description);

		$learn_more  = sprintf(
			'<a href="%s">%s</a>',
			esc_url(__('https://developers.google.com/search/docs/crawling-indexing/sitemaps/video-sitemaps')),
			esc_xml(__('Learn more about video sitemaps.', 'mihdan-index-now'))
		);

		$text = sprintf(
			/* translators: %s: Number of URLs. */
			esc_xml(__('Number of videos in this XML Sitemap: %s.', 'mihdan-index-now')),
			'<xsl:value-of select="count( sitemap:urlset/sitemap:url )" />'
		);

		$lang        = function_exists('get_language_attributes') ? get_language_attributes('html') : 'lang="en-US"';
		$video_col   = esc_xml(__('Video', 'mihdan-index-now'));
		$title_col   = esc_xml(__('Title', 'mihdan-index-now'));
		$url_col     = esc_xml(__('URL'));
		$desc_col    = esc_xml(__('Description', 'mihdan-index-now'));

		$xsl_content = <<<XSL
<?xml version="1.0" encoding="UTF-8"?>
<xsl:stylesheet
		version="1.0"
		xmlns:xsl="http://www.w3.org/1999/XSL/Transform"
		xmlns:sitemap="http://www.sitemaps.org/schemas/sitemap/0.9"
		xmlns:video="http://www.google.com/schemas/sitemap-video/1.1"
		exclude-result-prefixes="sitemap video"
		>

	<xsl:output method="html" encoding="UTF-8" indent="yes" />

	<xsl:variable name="has-thumbnail"   select="count( /sitemap:urlset/sitemap:url/video:video/video:thumbnail_loc )" />
	<xsl:variable name="has-description" select="count( /sitemap:urlset/sitemap:url/video:video/video:description )" />

	<xsl:template match="/">
		<html {$lang}>
			<head>
				<title>{$title}</title>
				<style>
					{$css}
				</style>
			</head>
			<body>
				<div id="sitemap">
					<div id="sitemap__header">
						<h1>{$title}</h1>
						<p>{$description}</p>
						<p>{$learn_more}</p>
					</div>
					<div id="sitemap__content">
						<p class="text">{$text}</p>
						<table id="sitemap__table">
							<thead>
								<tr>
									<xsl:if test="\$has-thumbnail">
										<th class="thumbnail">{$video_col}</th>
									</xsl:if>
									<th class="video-title">{$title_col}</th>
									<th class="loc">{$url_col}</th>
									<xsl:if test="\$has-description">
										<th class="video-desc">{$desc_col}</th>
									</xsl:if>
								</tr>
							</thead>
							<tbody>
								<xsl:for-each select="sitemap:urlset/sitemap:url">
									<tr>
										<xsl:if test="\$has-thumbnail">
											<td class="thumbnail">
												<xsl:if test="video:video/video:thumbnail_loc">
													<img src="{video:video/video:thumbnail_loc}" alt="" width="120" style="max-width:120px;height:auto;border-radius:4px;display:block;" />
												</xsl:if>
											</td>
										</xsl:if>
										<td class="video-title">
											<strong><xsl:value-of select="video:video/video:title" /></strong>
										</td>
										<td class="loc">
											<a href="{sitemap:loc}"><xsl:value-of select="sitemap:loc" /></a>
										</td>
										<xsl:if test="\$has-description">
											<td class="video-desc">
												<xsl:value-of select="video:video/video:description" />
											</td>
										</xsl:if>
									</tr>
								</xsl:for-each>
							</tbody>
						</table>
					</div>
				</div>
			</body>
		</html>
	</xsl:template>
</xsl:stylesheet>

XSL;

		$xsl_content = apply_filters('crawlwp_sitemaps_video_stylesheet_content', $xsl_content);

		return (string) apply_filters('wp_sitemaps_stylesheet_content', $xsl_content);
	}

